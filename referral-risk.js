/* ==========================================================================
   Privacy-preserving tokens
   --------------------------------------------------------------------------
   The prototype uses FNV-1a so the behaviour is inspectable offline.
   PRODUCTION MUST USE HMAC-SHA256 WITH A SERVER-SIDE SECRET PEPPER, and the
   token must never be computed in the browser — otherwise a client could
   enumerate the token space and recover the IP.
   ========================================================================== */

/** FNV-1a, 32-bit. Prototype only — see the note above. */
function fnv1a(str) {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i += 1) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

const toToken = (prefix, value) => {
  if (!value) return null;
  const a = fnv1a(`${prefix}:${value}`).toString(36).padStart(7, '0');
  const b = fnv1a(`${prefix}:${value}:salt`).toString(36).padStart(7, '0');
  return `${a}${b}`.slice(0, 10).toUpperCase();
};

/**
 * Non-reversible network token for an IP address.
 * Two accounts on the same address produce the same token, which is all the
 * admin view needs — the address itself is never stored or displayed.
 */
export const netToken = (ip) => toToken('net', ip);

/**
 * Non-reversible token for the APPLICATION-ASSIGNED Device ID.
 * This is not a fingerprint: the ID is generated by the app, stored by the
 * app, and carries no information about the underlying hardware.
 */
export const devToken = (deviceId) => toToken('dev', deviceId);

/** Phone: keep the country and a comparison token, never the number. */
export const phoneToken = (msisdn) => toToken('tel', msisdn);

/** Email: keep the domain and a comparison token, never the address. */
export const emailToken = (email) => toToken('eml', String(email || '').toLowerCase().trim());

export function emailParts(email) {
  const raw = String(email || '').toLowerCase().trim();
  const at = raw.lastIndexOf('@');
  if (at < 1) return { domain: null, local: null, token: null };
  return {
    domain: raw.slice(at + 1),
    local: raw.slice(0, at),
    token: emailToken(raw),
  };
}

/** Normalises a Nigerian number to +234XXXXXXXXXX, or returns null. */
export function normaliseNgPhone(input) {
  const digits = String(input || '').replace(/[^\d+]/g, '');
  if (!digits) return null;
  let d = digits.replace(/^\+/, '');
  if (d.startsWith('234')) d = d.slice(3);
  else if (d.startsWith('0')) d = d.slice(1);
  if (d.length !== 10) return null;
  // Nigerian mobile prefixes (070/080/081/090/091 → 70/80/81/90/91)
  if (!/^[789]0/.test(d)) return null;
  return `+234${d}`;
}

/** Dice coefficient over character bigrams — a cheap local-part similarity. */
export function similarity(a, b) {
  const s1 = String(a || '').toLowerCase().replace(/[^a-z0-9]/g, '');
  const s2 = String(b || '').toLowerCase().replace(/[^a-z0-9]/g, '');
  if (!s1 || !s2) return 0;
  if (s1 === s2) return 1;
  if (s1.length < 2 || s2.length < 2) return 0;
  const grams = (s) => {
    const out = new Map();
    for (let i = 0; i < s.length - 1; i += 1) {
      const g = s.slice(i, i + 2);
      out.set(g, (out.get(g) || 0) + 1);
    }
    return out;
  };
  const g1 = grams(s1);
  const g2 = grams(s2);
  let hits = 0;
  for (const [g, n] of g1) if (g2.has(g)) hits += Math.min(n, g2.get(g));
  return (2 * hits) / ((s1.length - 1) + (s2.length - 1));
}

