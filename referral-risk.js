/* ==========================================================================
   Network classification
   --------------------------------------------------------------------------
   VPN / proxy / Tor / hosting status is derived SERVER-SIDE from the
   connection, never from anything the browser reports about itself.
   ========================================================================== */
export function classifyNetwork({ asnType = null, torExit = false, vpnProvider = false, proxyHeaders = false } = {}) {
  return {
    tor: Boolean(torExit),
    vpn: Boolean(vpnProvider),
    proxy: Boolean(proxyHeaders),
    hosting: asnType === 'hosting' || asnType === 'datacenter',
  };
}
