export const SIGNAL_BY_ID = Object.fromEntries(REFERRAL_SIGNALS.map((s) => [s.id, s]));

/**
 * The most the IP signal can ever contribute, no matter how many accounts
 * share the address. This is the guarantee that a shared network alone can
 * never flag a referral.
 */
export const IP_ONLY_MAX_CONTRIBUTION = 6;

/** Decision thresholds. */
export const RISK_THRESHOLDS = {
  /** Below this the referral may be auto-verified (the server still credits). */
  AUTO_VERIFY: 35,
  /** At or above this the referral is held for the Super Admin. */
  HIGH_RISK: 70,
};

/* ==========================================================================
   Evaluation
   ========================================================================== */

/**
 * Scores a referral from its signals.
 *
 * @param {object} input
 * @param {string|null} input.referrerDeviceToken  app-assigned Device ID token
 * @param {string|null} input.refereeDeviceToken
 * @param {string|null} input.referrerPhoneToken
 * @param {string|null} input.refereePhoneToken
 * @param {string}      input.referrerEmailLocal
 * @param {string}      input.refereeEmailLocal
 * @param {string|null} input.referrerEmailDomain
 * @param {string|null} input.refereeEmailDomain
 * @param {boolean}     input.vpn
 * @param {boolean}     input.proxy
 * @param {boolean}     input.tor
 * @param {boolean}     input.hosting
 * @param {number}      input.refereeAccountAgeHours
 * @param {number}      input.minAccountAgeHours
 * @param {number}      input.ipOverlapCount     accounts sharing this network
 * @param {number}      input.deviceOverlapCount accounts sharing this Device ID
 * @param {number|null} input.signupDelayMinutes
 * @returns {{score:number, level:string, outcome:string, indicators:Array, reason:string}}
 */
export function evaluateReferral(input) {
  const {
    referrerDeviceToken = null,
    refereeDeviceToken = null,
    referrerPhoneToken = null,
    refereePhoneToken = null,
    referrerEmailLocal = '',
    refereeEmailLocal = '',
    referrerEmailDomain = null,
    refereeEmailDomain = null,
    vpn = false,
    proxy = false,
    tor = false,
    hosting = false,
    refereeAccountAgeHours = 0,
    minAccountAgeHours = 24,
    ipOverlapCount = 1,
    deviceOverlapCount = 1,
    signupDelayMinutes = null,
  } = input;

  const hits = [];
  const add = (id, evidence) => hits.push({ id, ...SIGNAL_BY_ID[id], evidence });

  if (referrerDeviceToken && refereeDeviceToken && referrerDeviceToken === refereeDeviceToken) {
    add('same_device', 'Identical Device ID on both accounts.');
  }
  if (referrerPhoneToken && refereePhoneToken && referrerPhoneToken === refereePhoneToken) {
    add('same_phone', 'Identical phone number on both accounts.');
  }
  if (tor) add('tor', 'Matched a known Tor exit node.');
  if (hosting) add('hosting', 'Matched a hosting/datacenter range.');
  if (proxy) add('proxy', 'Proxy behaviour detected on the connection.');
  if (vpn) add('vpn', 'VPN detected. Weak on its own.');

  if (referrerEmailLocal && refereeEmailLocal) {
    const sim = similarity(referrerEmailLocal, refereeEmailLocal);
    if (sim >= 0.85) add('email_similar', `Local parts ${(sim * 100).toFixed(0)}% similar.`);
    else if (referrerEmailDomain && referrerEmailDomain === refereeEmailDomain) {
      add('email_domain_match', `Both use @${refereeEmailDomain}.`);
    }
  }

  if (refereeAccountAgeHours < minAccountAgeHours) {
    add('young_account', `Account is ${refereeAccountAgeHours}h old; the minimum is ${minAccountAgeHours}h.`);
  }
  if (!refereePhoneToken) add('phone_missing', 'No phone number recorded.');

  // IP overlap is capped so a shared network can never dominate the score.
  if (ipOverlapCount >= 3) {
    add('ip_overlap', `${ipOverlapCount} accounts share this network.`);
  }
  if (deviceOverlapCount >= 3) {
    add('device_overlap', `${deviceOverlapCount} accounts share this Device ID.`);
  }
  if (signupDelayMinutes != null && signupDelayMinutes >= 0 && signupDelayMinutes <= 10) {
    add('instant_signup', `Signed up ${signupDelayMinutes} min after the invite was generated.`);
  }

  // Sum, but hold the network signal to its ceiling.
  let score = 0;
  let ipContribution = 0;
  for (const h of hits) {
    if (h.id === 'ip_overlap') {
      const capped = Math.min(h.weight, IP_ONLY_MAX_CONTRIBUTION - ipContribution);
      ipContribution += capped;
      score += capped;
    } else {
      score += h.weight;
    }
  }
  score = Math.min(100, score);

  let outcome = REVIEW_OUTCOME.AUTO_VERIFY;
  if (score >= RISK_THRESHOLDS.HIGH_RISK) outcome = REVIEW_OUTCOME.HIGH_RISK;
  else if (score >= RISK_THRESHOLDS.AUTO_VERIFY) outcome = REVIEW_OUTCOME.MANUAL_REVIEW;

  const level = score >= RISK_THRESHOLDS.HIGH_RISK ? 'high'
    : score >= RISK_THRESHOLDS.AUTO_VERIFY ? 'medium' : 'low';

  return {
    score,
    /**
     * How much of the score came from the network signal. Exposed so the
     * "a shared IP is never fraud on its own" guarantee can be asserted
     * directly instead of being inferred from a total that other signals
     * also contribute to.
     */
    ipContribution,
    level,
    outcome,
    indicators: hits.sort((a, b) => b.weight - a.weight),
    reason: hits.length
      ? hits.map((h) => h.label).join('; ')
      : 'No risk indicators detected.',
  };
}

