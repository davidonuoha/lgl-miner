/* ==========================================================================
   $LGL Miner — REFERRAL RISK ENGINE
   --------------------------------------------------------------------------
   Self-referral and referral-fraud detection.

   ┌───────────────────────────────────────────────────────────────────────┐
   │  NO FINGERPRINTING OF ANY KIND.                                       │
   │                                                                       │
   │  This module must never implement browser fingerprinting, device      │
   │  fingerprinting, canvas fingerprinting, WebGL/audio fingerprinting,   │
   │  font enumeration, screen-resolution hashing or any similar           │
   │  passive-identification technique.                                    │
   │                                                                       │
   │  The only device identifier used is the Device ID the application     │
   │  itself assigns and recognises on first run. Nothing is read from the │
   │  browser to try to identify the underlying hardware.                  │
   └───────────────────────────────────────────────────────────────────────┘

   Signals used, and nothing else:

     IP address            → reduced to a network token before it is stored
     Device ID             → the app-assigned ID, reduced to a device token
     Email                 → domain + local-part similarity, never the address
     Nigerian phone number → country + a shared-number comparison
     Referral relationship → who referred whom, and when
     Account history       → age, prior flags, prior reviews
     Network classification→ VPN / proxy / Tor / hosting / datacenter
     Activity patterns     → timing, volume, velocity

   PRIVACY RULES ENFORCED HERE
     · Raw IPs and raw Device IDs never leave this module's callers.
       `netToken()` / `devToken()` return truncated, non-reversible tokens.
     · No caller ever receives another user's IP or Device ID.
     · Only the minimum needed for fraud prevention is retained.

   A SINGLE SHARED IP IS NOT FRAUD. Legitimate users share home networks,
   offices, campuses and mobile carriers. The IP signal is deliberately
   weighted so that it can never, on its own, flag a referral. See
   IP_ONLY_MAX_CONTRIBUTION and the accompanying self-test.
   ========================================================================== */

